"""tour_shots.py --only keeps every picture it didn't retake.

Nov 2 2026: retaking the three job-code pictures from a folder that held only them rewrote the manifest with those
three, dropping the other eleven. Run: python3 scripts/test_tour_shots.py
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tour_shots as t  # noqa: E402

FAILS: list[str] = []


def check(label, got, want):
    if got != want:
        FAILS.append(f"FAIL {label}: got {got!r}, want {want!r}")


MANIFEST = """// Generated by scripts/tour_shots.py from the tour captures; do not edit by hand.
import type { WindowShots } from "./AppWindow";

export type TourSurface =
  | "hub"
  | "job-card"
;

export const TOUR_SHOTS: Record<TourSurface, WindowShots> = {
  "hub": {
    light: { src: "/images/for-attorneys/hub-light.webp", width: 1800, height: 940 },
    narrowLight: { src: "/images/for-attorneys/hub-light-phone.webp", width: 732, height: 1166 },
  },
  "job-card": {
    light: { src: "/images/for-attorneys/job-card-light.webp", width: 1632, height: 722 },
  },
};
"""


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        caps, out = root / "caps", root / "out"
        caps.mkdir()
        Image.new("RGB", (400, 200), "white").save(caps / "job-card-light.png")
        (caps / "crops.json").write_text(json.dumps({"job-card-light": {"capture": "job-card-light", "crop": None}}))
        manifest = root / "tourShots.ts"
        manifest.write_text(MANIFEST)
        t.MANIFEST, t.OUT, t.ROOT = manifest, out, root

        check("the manifest reader finds both pictures", list(t.read_manifest(MANIFEST)), ["hub", "job-card"])
        t.main(str(caps), {"job-card"})
        after = t.read_manifest(manifest.read_text())
        check("a picture not retaken keeps its entries", after.get("hub"), t.read_manifest(MANIFEST)["hub"])
        check("the retaken one carries its new size", after.get("job-card", {}).get("light"),
              ("/images/for-attorneys/job-card-light.webp", 400, 200))
        check("and both stay typed", "\"hub\"" in manifest.read_text().split("TOUR_SHOTS")[0], True)

    for f in FAILS:
        print(f)
    print("all checks passed" if not FAILS else f"{len(FAILS)} failed")
    return 1 if FAILS else 0


if __name__ == "__main__":
    sys.exit(main())
