"""Crop and encode the app's product pictures, and write their manifest.

The captures and their crops come from scripts/capture-tour.mjs, which loads
the "Tour/" and "Home/Attorney hero timeline" stories with the clock fixed to
the recording's day and measures each crop from the page's own headings:

    node scripts/capture-tour.mjs <captures-folder>
    python3 scripts/tour_shots.py <captures-folder> [--only picture,picture]

`--only` rebuilds just those pictures; every other one is left as it is and
keeps its manifest entry, read from the file on disk. Writes
public/images/for-attorneys/<picture>-<theme>[-phone].webp and
src/components/marketing/tourShots.ts, which declares each file's real size.
A picture marked `guide` is a figure in the guides: light only, outside the
manifest.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public/images/for-attorneys"
MANIFEST = ROOT / "src/components/marketing/tourShots.ts"
SCALE = 2  # the captures are at device scale 2
WIDE_WIDTH = 1800  # twice the widest the frame is drawn
QUALITY = 85


def encode(src: Path, crop: list[int] | None, width: int | None, out: Path) -> tuple[int, int]:
    im = Image.open(src).convert("RGB")
    if crop:
        left, top, right, bottom = crop
        im = im.crop((SCALE * left, SCALE * top, min(SCALE * right, im.width), min(SCALE * bottom, im.height)))
    if width and im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    out.parent.mkdir(parents=True, exist_ok=True)
    im.save(out, "WEBP", quality=QUALITY, method=6)
    return im.size


def manifest_key(theme: str, phone: bool) -> str:
    return f"narrow{theme.title()}" if phone else theme


ENTRY = re.compile(r'(\w+): \{ src: "([^"]+)", width: (\d+), height: (\d+) \}')


def read_manifest(text: str) -> dict[str, dict[str, tuple[str, int, int]]]:
    """The pictures the manifest on disk declares, in its order."""
    shots: dict[str, dict[str, tuple[str, int, int]]] = {}
    current: str | None = None
    for line in text.splitlines():
        head = re.match(r'\s*"([\w-]+)": \{\s*$', line)
        if head:
            current = head.group(1)
            shots[current] = {}
            continue
        entry = ENTRY.search(line)
        if current and entry:
            shots[current][entry.group(1)] = (entry.group(2), int(entry.group(3)), int(entry.group(4)))
    return shots


def main(folder: str, only: set[str] | None = None) -> int:
    src = Path(folder)
    crops: dict[str, dict] = json.loads((src / "crops.json").read_text())
    # `--only` starts from the manifest on disk: a folder holding only the pictures being retaken would otherwise
    # drop every other picture's entry (Nov 2 2026: retaking the three job-code pictures emptied the rest).
    shots: dict[str, dict[str, tuple[str, int, int]]] = (
        {k: v for k, v in read_manifest(MANIFEST.read_text()).items() if k not in only}
        if only is not None and MANIFEST.exists()
        else {}
    )
    # picture -> {(theme, phone): entry}
    pictures: dict[str, dict[tuple[str, bool], dict]] = {}
    for key, entry in crops.items():
        picture, theme = key.rsplit("-", 1)
        phone = picture.endswith("-phone")
        pictures.setdefault(picture.removesuffix("-phone"), {})[(theme, phone)] = entry

    for picture, variants in pictures.items():
        guide = any(v.get("guide") for v in variants.values())
        has_wide = any(not phone for _, phone in variants)
        for (theme, phone), entry in sorted(variants.items()):
            if guide and theme != "light":
                continue
            # A picture taken only at phone width (the case card) is its own picture, not a phone version.
            narrow = phone and has_wide
            name = f"{picture}-{theme}{'-phone' if narrow else ''}"
            out = OUT / f"{name}.webp"
            if only is not None and picture not in only:
                if out.exists() and not guide:
                    with Image.open(out) as im:
                        shots.setdefault(picture, {})[manifest_key(theme, narrow)] = (f"/images/for-attorneys/{name}.webp", *im.size)
                continue
            png = src / f"{entry['capture']}.png"
            if not png.exists():
                raise SystemExit(f"missing capture {png}")
            w, h = encode(png, entry["crop"], None if narrow else WIDE_WIDTH, out)
            print(f"{out.relative_to(ROOT)}  {w}x{h}  {out.stat().st_size // 1024} KB{' (guides)' if guide else ''}")
            if not guide:
                shots.setdefault(picture, {})[manifest_key(theme, narrow)] = (f"/images/for-attorneys/{name}.webp", w, h)
        if picture in shots and "dark" not in shots[picture] and "light" in shots[picture]:
            shots[picture]["dark"] = shots[picture]["light"]
    lines = [
        "// Generated by scripts/tour_shots.py from the tour captures; do not edit by hand.",
        'import type { WindowShots } from "./AppWindow";',
        "",
        "export type TourSurface =",
        *[f'  | "{s}"' for s in shots],
        ";",
        "",
        "export const TOUR_SHOTS: Record<TourSurface, WindowShots> = {",
    ]
    for surface, entries in shots.items():
        lines.append(f'  "{surface}": {{')
        for key in ("light", "dark", "narrowLight", "narrowDark"):
            if key in entries:
                path, w, h = entries[key]
                lines.append(f'    {key}: {{ src: "{path}", width: {w}, height: {h} }},')
        lines.append("  },")
    lines.append("};")
    MANIFEST.write_text("\n".join(lines) + "\n")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    args = sys.argv[1:]
    picked: set[str] | None = None
    if "--only" in args:
        i = args.index("--only")
        picked = {x for x in args[i + 1].split(",") if x}
        del args[i : i + 2]
    sys.exit(main(args[0], picked))
