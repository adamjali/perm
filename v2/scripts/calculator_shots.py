#!/usr/bin/env python3
"""Turn the calculator captures into the calculators page's pictures.

    CAPTURE_SPEC=scripts/page-pictures.json node scripts/capture_article_heroes.mjs <base> <dir>/light
    CAPTURE_SPEC=scripts/page-pictures.json CAPTURE_DARK=1 node scripts/capture_article_heroes.mjs <base> <dir>/dark
    python3 scripts/calculator_shots.py <dir>

Writes public/images/calculators/<name>-light.webp and -dark.webp (1800px wide, the attorney page's tour width)
and src/components/tools/calculatorShots.ts with each file's real size and the alt text from page-pictures.json.
"""

import json
import sys
from pathlib import Path

from PIL import Image

WIDTH = 1800
OUT = Path("public/images/calculators")
TS = Path("src/components/tools/calculatorShots.ts")


def main() -> int:
    src = Path(sys.argv[1])
    spec = json.loads(Path("scripts/page-pictures.json").read_text())
    names = [k.split("/", 1)[1] for k in spec if k.startswith("calculators/")]
    OUT.mkdir(parents=True, exist_ok=True)
    entries = []
    for name in names:
        sizes = {}
        for theme in ("light", "dark"):
            png = src / theme / "calculators" / f"{name}.png"
            if not png.exists():
                print(f"missing {png}", file=sys.stderr)
                return 1
            im = Image.open(png).convert("RGB")
            h = round(im.height * WIDTH / im.width)
            im = im.resize((WIDTH, h), Image.LANCZOS)
            dest = OUT / f"{name}-{theme}.webp"
            im.save(dest, "WEBP", quality=82, method=6)
            sizes[theme] = (h, dest.stat().st_size)
        alt = spec[f"calculators/{name}"]["alt"].replace("\\", "\\\\").replace('"', '\\"')
        entries.append((name, sizes, alt))
        print(f"{name}: {WIDTH}x{sizes['light'][0]} light {sizes['light'][1] // 1024} KB, dark {sizes['dark'][1] // 1024} KB")
    lines = [
        "// Generated by scripts/calculator_shots.py from the captures listed in scripts/page-pictures.json; do not edit by hand.",
        'import type { WindowShots } from "@/components/marketing/AppWindow";',
        "",
        "export type CalculatorShot = " + " | ".join(f'"{n}"' for n, _, _ in entries) + ";",
        "",
        "export const CALCULATOR_SHOTS: Record<CalculatorShot, { shots: WindowShots; alt: string }> = {",
    ]
    for name, sizes, alt in entries:
        lines += [
            f'  "{name}": {{',
            "    shots: {",
            f'      light: {{ src: "/images/calculators/{name}-light.webp", width: {WIDTH}, height: {sizes["light"][0]} }},',
            f'      dark: {{ src: "/images/calculators/{name}-dark.webp", width: {WIDTH}, height: {sizes["dark"][0]} }},',
            "    },",
            f'    alt: "{alt}",',
            "  },",
        ]
    lines += ["};", ""]
    TS.write_text("\n".join(lines))
    print(f"wrote {TS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
